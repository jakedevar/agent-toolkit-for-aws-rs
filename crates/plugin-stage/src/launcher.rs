//! Launcher side of the packaging contract.
//!
//! A launcher is a host configuration string that runs a staged binary: a
//! hook `command` in `hooks.json`, or an MCP server `command` in `.mcp.json`
//! or `mcp.json` (also inline in a plugin manifest). Launchers always call
//! the generated dispatcher `${CLAUDE_PLUGIN_ROOT}/bin/<name>`, never a
//! platform directory, and the dispatcher picks the binary for the running
//! platform. [`check_launchers`] proves every such reference resolves to a
//! declared binary and has the form its role requires.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Component, Path, PathBuf};

use toolkit_core::{parse_json, Json};

use crate::declaration::{BinarySpec, Declaration, Role};
use crate::BIN_DIR;

/// Plugin-root variables a launcher may start with.
pub const ROOT_VARS: [&str; 2] = ["CLAUDE_PLUGIN_ROOT", "CURSOR_PLUGIN_ROOT"];

/// Directories never scanned for launcher files: shipped skill content,
/// fixtures, tests, dependencies and the staged `bin/` directory itself.
const SKIP_DIRS: [&str; 7] = [
    "skills",
    "fixtures",
    "tests",
    "node_modules",
    "bin",
    "target",
    ".git",
];

/// Launcher configuration file names.
const LAUNCHER_FILES: [&str; 3] = ["hooks.json", ".mcp.json", "mcp.json"];

/// Plugin manifests that may point at, or inline, launcher configuration.
const MANIFESTS: [&str; 5] = [
    "plugin.json",
    ".claude-plugin/plugin.json",
    ".codex-plugin/plugin.json",
    ".cursor-plugin/plugin.json",
    ".devin-plugin/plugin.json",
];

/// The canonical fail-closed launcher of a guard hook: it runs the
/// dispatcher, forwards its output when it exits 0 and otherwise (missing
/// file, not executable, no binary for this platform, non-zero exit,
/// signal) prints a `PreToolUse` deny carrying `deny_reason`. This is the
/// #4412 launcher contract with the path moved to `bin/<name>`.
#[must_use]
pub fn guard_hook_command(root_var: &str, name: &str, deny_reason: &str) -> String {
    let deny = format!(
        r#"{{\"hookSpecificOutput\":{{\"hookEventName\":\"PreToolUse\",\"permissionDecision\":\"deny\",\"permissionDecisionReason\":\"{deny_reason}\"}}}}"#
    );
    format!(
        r#"sh -c 'if out=$("$0" 2>/dev/null); then printf %s "$out"; else printf %s "{deny}"; fi' "${{{root_var}}}/bin/{name}""#
    )
}

/// The canonical MCP server command of a staged binary.
#[must_use]
pub fn mcp_command(root_var: &str, name: &str) -> String {
    format!("${{{root_var}}}/bin/{name}")
}

/// The generated POSIX dispatcher staged at `bin/<name>`. It maps
/// `uname -s` / `uname -m` to one of the supported platform pairs, runs
/// `bin/<key>/<name>` (or `bin/<name>.exe` under Git Bash, MSYS or Cygwin on
/// Windows, `x86_64` or ARM64 through emulation) with the caller's arguments
/// and stdin, and exits 127 with a message on stderr when the platform is
/// unsupported (before any file lookup, #5025) or no binary is staged for it.
#[must_use]
pub fn dispatcher_script(name: &str) -> String {
    format!(
        r#"#!/bin/sh
# Generated by plugin-stage (#4487); do not edit. Runs the staged {name}
# binary for this platform. bin/manifest.json lists every staged file, its
# sha256 and the source commit it was built from.
case "$0" in */*) d=${{0%/*}} ;; *) d=. ;; esac
s=$(uname -s 2>/dev/null)
m=$(uname -m 2>/dev/null)
o=
a=
case "$s" in
  Linux) o=linux ;;
  Darwin) o=macos ;;
  MINGW*|MSYS*|CYGWIN*) o=windows ;;
esac
case "$m" in
  x86_64|amd64|x64) a=x86_64 ;;
  aarch64|arm64) a=aarch64 ;;
esac
if [ -z "$o" ] || [ -z "$a" ]; then
  printf '%s: unsupported platform (uname -s %s, uname -m %s); no staged binary runs here\n' "{name}" "$s" "$m" >&2
  exit 127
fi
if [ "$o" = windows ]; then b="$d/{name}.exe"; else b="$d/$o-$a/{name}"; fi
if [ ! -f "$b" ] || [ ! -x "$b" ]; then
  echo "{name}: no staged binary for $o-$a at $b; reinstall the plugin" >&2
  exit 127
fi
exec "$b" "$@"
"#
    )
}

/// A JSON launcher snippet for one declared binary, ready to paste into
/// `hooks.json` (guard and hook roles) or `.mcp.json` (MCP role).
#[must_use]
pub fn launcher_snippet(binary: &BinarySpec) -> String {
    let root = ROOT_VARS[0];
    let value = match &binary.role {
        Role::GuardHook { deny_reason } => Json::object(vec![
            ("type", Json::string("command")),
            (
                "command",
                Json::string(guard_hook_command(root, &binary.name, deny_reason)),
            ),
            ("timeout", Json::Int(5)),
        ]),
        Role::McpServer => Json::object(vec![
            ("type", Json::string("stdio")),
            ("command", Json::string(mcp_command(root, &binary.name))),
            ("args", Json::Array(Vec::new())),
        ]),
        Role::Hook => Json::object(vec![
            ("type", Json::string("command")),
            (
                "command",
                Json::string(format!("\"{}\"", mcp_command(root, &binary.name))),
            ),
        ]),
    };
    value.to_pretty_string()
}

/// Which host configuration a launcher string came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Hooks,
    Mcp,
}

/// One validated launcher reference.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LauncherRef {
    /// Plugin directory name.
    pub plugin: String,
    /// Declared binary name.
    pub name: String,
    /// Repository-relative launcher file and JSON path.
    pub location: String,
}

/// Result of [`check_launchers`].
#[derive(Debug, Default)]
pub struct LauncherReport {
    /// Contract violations; empty means the contract holds.
    pub problems: Vec<String>,
    /// Every valid reference to a declared binary.
    pub references: Vec<LauncherRef>,
    /// Number of launcher files scanned.
    pub files_scanned: usize,
}

impl LauncherReport {
    /// Declared binaries no launcher references yet (informational: a
    /// binary may be staged before its launcher switch lands).
    #[must_use]
    pub fn unreferenced<'a>(&self, declaration: &'a Declaration) -> Vec<&'a BinarySpec> {
        declaration
            .binaries
            .iter()
            .filter(|binary| {
                !self
                    .references
                    .iter()
                    .any(|r| r.plugin == binary.plugin && r.name == binary.name)
            })
            .collect()
    }
}

/// Scans every plugin under `plugins_root` and checks that each launcher
/// reference to a `bin/` entry names a binary `declaration` declares for that
/// plugin, goes through the dispatcher and has the form its role requires.
/// `repo_root` only shortens paths in messages.
#[must_use]
pub fn check_launchers(
    repo_root: &Path,
    plugins_root: &Path,
    declaration: &Declaration,
) -> LauncherReport {
    let mut report = LauncherReport::default();
    let mut plugins: Vec<PathBuf> = match fs::read_dir(plugins_root) {
        Ok(entries) => entries
            .filter_map(Result::ok)
            .map(|entry| entry.path())
            .filter(|path| path.is_dir())
            .collect(),
        Err(err) => {
            report.problems.push(format!(
                "{}: cannot read plugins directory: {err}",
                plugins_root.display()
            ));
            return report;
        }
    };
    plugins.sort();
    for plugin_dir in plugins {
        let plugin = plugin_dir
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default();
        let scan = PluginScan {
            repo_root,
            plugin_dir: &plugin_dir,
            plugin: &plugin,
            declaration,
        };
        scan.run(&mut report);
    }
    for plugin in declaration.plugins() {
        if !plugins_root.join(plugin).is_dir() {
            report.problems.push(format!(
                "{DECLARATION}: plugin {plugin} has no directory under {}",
                display(repo_root, plugins_root),
                DECLARATION = crate::DECLARATION_PATH
            ));
        }
    }
    report
}

struct PluginScan<'a> {
    repo_root: &'a Path,
    plugin_dir: &'a Path,
    plugin: &'a str,
    declaration: &'a Declaration,
}

impl PluginScan<'_> {
    fn run(&self, report: &mut LauncherReport) {
        let mut files = BTreeMap::new();
        collect_launcher_files(self.plugin_dir, &mut files);
        let mut inline = Vec::new();
        for manifest in MANIFESTS {
            let path = self.plugin_dir.join(manifest);
            if !path.is_file() {
                continue;
            }
            let rel = display(self.repo_root, &path);
            match read_json(&path) {
                Ok(root) => {
                    let mut found = Vec::new();
                    manifest_refs(&root, &mut Vec::new(), &mut found);
                    for (json_path, target) in found {
                        match target {
                            ManifestRef::File(kind, text) => match self.resolve(&path, &text) {
                                Ok(file) => {
                                    files.insert(file, kind);
                                }
                                Err(message) => report
                                    .problems
                                    .push(format!("{rel}: {}: {message}", path_text(&json_path))),
                            },
                            ManifestRef::Inline(kind, value) => {
                                inline.push((
                                    format!("{rel}: {}", path_text(&json_path)),
                                    kind,
                                    value,
                                ));
                            }
                            ManifestRef::Malformed(message) => report
                                .problems
                                .push(format!("{rel}: {}: {message}", path_text(&json_path))),
                        }
                    }
                }
                Err(message) => report.problems.push(format!("{rel}: {message}")),
            }
        }
        for (file, kind) in files {
            let rel = display(self.repo_root, &file);
            report.files_scanned += 1;
            match read_json(&file) {
                Ok(root) => self.scan_value(&rel, kind, &root, &mut Vec::new(), report),
                Err(message) => report.problems.push(format!("{rel}: {message}")),
            }
        }
        for (location, kind, value) in inline {
            report.files_scanned += 1;
            self.scan_value(&location, kind, &value, &mut Vec::new(), report);
        }
    }

    /// Resolves a manifest's launcher file reference inside the plugin.
    fn resolve(&self, manifest: &Path, text: &str) -> Result<PathBuf, String> {
        let relative: PathBuf = Path::new(text)
            .components()
            .filter(|part| !matches!(part, Component::CurDir))
            .collect();
        if relative.is_absolute()
            || relative.components().any(|part| {
                matches!(
                    part,
                    Component::ParentDir | Component::Prefix(_) | Component::RootDir
                )
            })
        {
            return Err(format!("launcher file {text:?} points outside the plugin"));
        }
        let from_root = self.plugin_dir.join(&relative);
        if from_root.is_file() {
            return Ok(from_root);
        }
        let from_manifest = manifest.parent().map(|dir| dir.join(&relative));
        match from_manifest {
            Some(path) if path.is_file() => Ok(path),
            _ => Err(format!("launcher file {text:?} does not exist")),
        }
    }

    fn scan_value(
        &self,
        location: &str,
        kind: Kind,
        value: &Json,
        json_path: &mut Vec<String>,
        report: &mut LauncherReport,
    ) {
        match value {
            Json::String(text) => self.scan_string(location, kind, text, json_path, report),
            Json::Array(items) => {
                for (index, item) in items.iter().enumerate() {
                    json_path.push(format!("[{index}]"));
                    self.scan_value(location, kind, item, json_path, report);
                    json_path.pop();
                }
            }
            Json::Object(pairs) => {
                for (key, item) in pairs {
                    json_path.push(key.clone());
                    self.scan_value(location, kind, item, json_path, report);
                    json_path.pop();
                }
            }
            _ => {}
        }
    }

    fn scan_string(
        &self,
        location: &str,
        kind: Kind,
        text: &str,
        json_path: &[String],
        report: &mut LauncherReport,
    ) {
        let at = format!("{location}: {}", path_text(json_path));
        match self.resolve_string(kind, text, json_path) {
            Ok(None) => {}
            Ok(Some(name)) => report.references.push(LauncherRef {
                plugin: self.plugin.to_string(),
                name,
                location: at,
            }),
            Err(message) => report.problems.push(format!("{at}: {message}")),
        }
    }

    /// Resolves one launcher string, failing closed (#5022): a string that
    /// mentions a plugin `bin/` path is accepted only when it is exactly one
    /// canonical launcher form of a declared binary, or names exactly one
    /// declared `bin/<name>` in a spelling the checker resolves; any other
    /// spelling (quoted, relative, wrapped, through a variable, `.`/`..`
    /// segments, globs, a second reference) is refused. `Ok(None)` means the
    /// string mentions no plugin binary.
    fn resolve_string(
        &self,
        kind: Kind,
        text: &str,
        json_path: &[String],
    ) -> Result<Option<String>, String> {
        if let Some(binary) = self.canonical_binary(text) {
            return match role_problem(binary, kind, text, json_path) {
                Some(message) => Err(message),
                None => Ok(Some(binary.name.clone())),
            };
        }
        let mentions = plugin_bin_mentions(text);
        if mentions.is_empty() {
            return Ok(None);
        }
        let launcher_hint = "print the canonical launcher with `plugin-stage launcher PLUGIN/NAME`";
        if let Some(reason) = mentions.iter().find_map(|mention| match mention {
            Mention::Unresolvable(reason) => Some(reason),
            Mention::Bin(_) => None,
        }) {
            return Err(format!(
                "{reason}; plugin-stage cannot resolve it to one canonical launcher, so it is refused (fail closed); {launcher_hint}"
            ));
        }
        if mentions.len() > 1 {
            return Err(format!(
                "mentions {} plugin bin/ paths; a launcher runs exactly one binary through its canonical form; {launcher_hint}",
                mentions.len()
            ));
        }
        let name = match find_bin_refs(text).as_slice() {
            [Found::Bad(message)] => return Err(message.clone()),
            [Found::Name(name)]
                if mentions[0] == Mention::Bin(format!("{BIN_DIR}/{name}")) =>
            {
                name.clone()
            }
            _ => {
                return Err(format!(
                    "mentions a plugin bin/ path in a quoted, relative, wrapped or otherwise non-canonical spelling; plugin-stage cannot resolve it to one canonical launcher, so it is refused (fail closed); {launcher_hint}"
                ))
            }
        };
        let Some(binary) = self.declaration.binary(self.plugin, &name) else {
            return Err(format!(
                "references bin/{name}, which {} does not declare for plugin {}",
                crate::DECLARATION_PATH,
                self.plugin
            ));
        };
        match role_problem(binary, kind, text, json_path) {
            Some(message) => Err(message),
            None => Ok(Some(name)),
        }
    }

    /// The declared binary of this plugin whose canonical launcher `text` is
    /// byte for byte, if any.
    fn canonical_binary(&self, text: &str) -> Option<&BinarySpec> {
        self.declaration
            .plugin_binaries(self.plugin)
            .find(|binary| canonical_forms(binary).iter().any(|form| form == text))
    }
}

/// The exact launcher strings a binary's role allows.
fn canonical_forms(binary: &BinarySpec) -> Vec<String> {
    let name = &binary.name;
    match &binary.role {
        Role::GuardHook { deny_reason } => ROOT_VARS
            .iter()
            .map(|root| guard_hook_command(root, name, deny_reason))
            .collect(),
        Role::McpServer => ROOT_VARS
            .iter()
            .map(|root| mcp_command(root, name))
            .chain([format!("./{BIN_DIR}/{name}")])
            .collect(),
        Role::Hook => ROOT_VARS
            .iter()
            .map(|root| format!("\"{}\"", mcp_command(root, name)))
            .collect(),
    }
}

/// How a launcher string mentions the plugin `bin/` directory.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Mention {
    /// A statically resolved path below the plugin root starting at `bin`,
    /// for example `bin/tool`.
    Bin(String),
    /// A path that may reach the plugin `bin/` but cannot be resolved.
    Unresolvable(String),
}

/// Characters that make a path segment dynamic (expansion or globbing).
const DYNAMIC: &[char] = &['$', '*', '?', '[', ']', '{', '}', '~', '`'];

/// Glob characters that can make a relative path expand to `bin/...`.
const GLOB: &[char] = &['*', '?', '['];

/// Characters that separate shell words or commands, after quotes are
/// removed. Splitting on them is deliberately coarse: it may produce more
/// candidate paths than the shell would, never fewer.
const SEPARATORS: &[char] = &[';', '|', '&', '(', ')', '<', '>', '=', '`', ','];

/// Every place `text` may name the plugin `bin/` directory, found
/// conservatively: quotes are dropped (the shell concatenates `"a"b`),
/// backslashes are read as escapes (and, separately, as Windows path
/// separators), and the string is split into candidate paths. A plugin-root
/// path (`${CLAUDE_PLUGIN_ROOT}/...`), a path under another variable and a
/// relative path (`bin/x`, `./bin/x`, `../bin/x`) are all considered; an
/// absolute system path such as `/usr/bin/env` is not.
fn plugin_bin_mentions(text: &str) -> Vec<Mention> {
    let unquoted: String = text.chars().filter(|c| !matches!(c, '"' | '\'')).collect();
    let mut mentions = scan_words(&unquoted.replace('\\', ""));
    if unquoted.contains('\\') {
        let separated = scan_words(&unquoted.replace('\\', "/"));
        if separated
            .iter()
            .any(|mention| matches!(mention, Mention::Bin(_)) && !mentions.contains(mention))
        {
            mentions.push(Mention::Unresolvable(
                "uses a backslash in a path that may name the plugin bin/ directory".to_string(),
            ));
        }
    }
    mentions
}

fn scan_words(text: &str) -> Vec<Mention> {
    text.split(|c: char| c.is_whitespace() || SEPARATORS.contains(&c))
        .filter(|word| !word.is_empty())
        .filter_map(word_mention)
        .collect()
}

fn is_bin_segment(segment: &str) -> bool {
    let head = segment.split(':').next().unwrap_or(segment);
    head.eq_ignore_ascii_case(BIN_DIR)
}

fn is_root_var(segment: &str) -> bool {
    ROOT_VARS
        .iter()
        .any(|root| segment == format!("${{{root}}}") || segment == format!("${root}"))
}

fn word_mention(word: &str) -> Option<Mention> {
    let segments: Vec<&str> = word.split('/').collect();
    let root = segments
        .iter()
        .rposition(|segment| ROOT_VARS.iter().any(|root| segment.contains(root)));
    if let Some(index) = root {
        let rest = &segments[index + 1..];
        if rest.iter().all(|segment| segment.is_empty()) {
            return None;
        }
        if !is_root_var(segments[index]) {
            return Some(Mention::Unresolvable(format!(
                "uses the plugin root in {word:?} through an expansion other than a plain ${{CLAUDE_PLUGIN_ROOT}}"
            )));
        }
        return plugin_path(word, rest);
    }
    if segments.first() == Some(&"") {
        // An absolute path (`/usr/bin/env`) is not inside the plugin.
        return None;
    }
    let Some(index) = segments.iter().position(|segment| is_bin_segment(segment)) else {
        // No literal bin segment; a glob before the last segment may still
        // expand to one (`b?n/tool`).
        let leading = &segments[..segments.len() - 1];
        return leading
            .iter()
            .any(|segment| segment.contains(GLOB))
            .then(|| {
                Mention::Unresolvable(format!(
                    "{word:?} is a globbed path that may name the plugin bin/ directory"
                ))
            });
    };
    let leading = &segments[..index];
    if leading.iter().any(|segment| segment.contains(DYNAMIC)) {
        Some(Mention::Unresolvable(format!(
            "{word:?} reaches a bin/ directory through a variable, glob or expansion"
        )))
    } else if leading.iter().all(|segment| *segment == ".") {
        plugin_path(word, &segments[index..])
    } else if leading.contains(&"..") {
        Some(Mention::Unresolvable(format!(
            "{word:?} is a relative path with `..` that may name the plugin bin/ directory"
        )))
    } else {
        None
    }
}

/// Classifies the segments of a path below the plugin root: only its first
/// real segment decides whether it is the plugin `bin/` directory, and `..`
/// anywhere could re-enter it.
fn plugin_path(word: &str, rest: &[&str]) -> Option<Mention> {
    if rest.contains(&"..") {
        return Some(Mention::Unresolvable(format!(
            "{word:?} has a `..` segment in its plugin path"
        )));
    }
    let parts: Vec<&str> = rest
        .iter()
        .copied()
        .filter(|segment| !segment.is_empty() && *segment != ".")
        .collect();
    match parts.first() {
        Some(first) if first.contains(DYNAMIC) => Some(Mention::Unresolvable(format!(
            "{word:?} has a variable, glob or expansion in its plugin path"
        ))),
        Some(first) if is_bin_segment(first) => Some(Mention::Bin(parts.join("/"))),
        _ => None,
    }
}

/// Checks the launcher form a binary's role requires.
fn role_problem(
    binary: &BinarySpec,
    kind: Kind,
    text: &str,
    json_path: &[String],
) -> Option<String> {
    let name = &binary.name;
    if json_path.last().map(String::as_str) != Some("command") {
        return Some(format!(
            "bin/{name} may only appear in a launcher `command` field"
        ));
    }
    match (&binary.role, kind) {
        (Role::GuardHook { deny_reason }, Kind::Hooks) => {
            if !json_path.iter().any(|part| part == "PreToolUse") {
                return Some(format!(
                    "guard hook bin/{name} must be registered under PreToolUse"
                ));
            }
            let canonical = ROOT_VARS
                .iter()
                .any(|root| text == guard_hook_command(root, name, deny_reason));
            (!canonical).then(|| {
                format!(
                    "guard hook bin/{name} must use the canonical fail-closed launcher (print it with `plugin-stage launcher {}/{name}`)",
                    binary.plugin
                )
            })
        }
        (Role::McpServer, Kind::Mcp) => {
            let exact = ROOT_VARS.iter().any(|root| text == mcp_command(root, name))
                || text == format!("./{BIN_DIR}/{name}");
            (!exact).then(|| {
                format!("MCP server command must be exactly ${{CLAUDE_PLUGIN_ROOT}}/bin/{name}")
            })
        }
        (Role::Hook, Kind::Hooks) => None,
        (role, Kind::Hooks) => Some(format!(
            "bin/{name} is declared {} and cannot be launched from a hook",
            role.as_str()
        )),
        (role, Kind::Mcp) => Some(format!(
            "bin/{name} is declared {} and cannot be launched as an MCP server",
            role.as_str()
        )),
    }
}

/// A `bin/` reference inside one launcher string.
#[derive(Debug, PartialEq, Eq)]
enum Found {
    Name(String),
    Bad(String),
}

/// Finds every reference to the plugin `bin/` directory in `text`:
/// `${CLAUDE_PLUGIN_ROOT}/bin...`, `${CURSOR_PLUGIN_ROOT}/bin...` (with or
/// without braces) anywhere, or a string that starts with `./bin/` or `bin/`.
fn find_bin_refs(text: &str) -> Vec<Found> {
    let mut found = Vec::new();
    let mut prefixes = Vec::new();
    for root in ROOT_VARS {
        prefixes.push(format!("${{{root}}}/{BIN_DIR}"));
        prefixes.push(format!("${root}/{BIN_DIR}"));
    }
    for prefix in &prefixes {
        let mut start = 0;
        while let Some(offset) = text[start..].find(prefix.as_str()) {
            let after = start + offset + prefix.len();
            if let Some(item) = classify(&text[after..]) {
                found.push(item);
            }
            start = after;
        }
    }
    for prefix in ["./bin", "bin"] {
        if let Some(rest) = text.strip_prefix(prefix) {
            if let Some(item) = classify(rest) {
                found.push(item);
            }
        }
    }
    found
}

/// Classifies the text that follows a `.../bin` prefix. `None` when the
/// prefix was part of a longer word (for example `bin2` or `binaries`).
fn classify(rest: &str) -> Option<Found> {
    let mut chars = rest.chars();
    match chars.next() {
        Some('/') => {}
        Some(c) if c.is_ascii_alphanumeric() || "-_.".contains(c) => return None,
        _ => {
            return Some(Found::Bad(
                "references the bin/ directory itself; launchers must name bin/<name>".to_string(),
            ))
        }
    }
    let token: String = rest[1..]
        .chars()
        .take_while(|c| !c.is_whitespace() && !"\"'`;|&()<>$".contains(*c))
        .collect();
    let bad = |message: String| Some(Found::Bad(message));
    if token.is_empty() {
        bad("references the bin/ directory itself; launchers must name bin/<name>".to_string())
    } else if token.contains('/') || token.contains('\\') {
        bad(format!(
            "references bin/{token} directly; launchers must call the dispatcher bin/<name>, which selects the platform binary"
        ))
    } else if token.to_ascii_lowercase().ends_with(".exe") {
        bad(format!(
            "references bin/{token} directly; launchers must call the dispatcher bin/<name>, which runs the .exe on Windows"
        ))
    } else if crate::declaration::is_name(&token) {
        Some(Found::Name(token))
    } else {
        bad(format!(
            "references bin/{token}, which is not a valid binary name"
        ))
    }
}

enum ManifestRef {
    File(Kind, String),
    Inline(Kind, Json),
    Malformed(String),
}

/// One `hooks` / `mcpServers` value or path-list member.
fn manifest_member(key: &str, kind: Kind, value: &Json) -> ManifestRef {
    match value {
        Json::String(text) => ManifestRef::File(kind, text.clone()),
        Json::Object(_) => ManifestRef::Inline(kind, value.clone()),
        other => ManifestRef::Malformed(format!(
            "`{key}` must be a file path, a list of file paths or inline configuration, not {}",
            json_type(other)
        )),
    }
}

fn json_type(value: &Json) -> &'static str {
    match value {
        Json::Null => "null",
        Json::Bool(_) => "a boolean",
        Json::String(_) => "a string",
        Json::Array(_) => "a nested list",
        Json::Object(_) => "an object",
        Json::Int(_) | Json::Float(_) => "a number",
    }
}

/// Collects `hooks` / `mcpServers` members of a plugin manifest: a string is
/// a launcher file path, an object is inline launcher configuration, and a
/// list holds either; any other value is malformed and reported.
fn manifest_refs(
    value: &Json,
    json_path: &mut Vec<String>,
    out: &mut Vec<(Vec<String>, ManifestRef)>,
) {
    match value {
        Json::Object(pairs) => {
            for (key, item) in pairs {
                json_path.push(key.clone());
                let kind = match key.as_str() {
                    "hooks" => Some(Kind::Hooks),
                    "mcpServers" => Some(Kind::Mcp),
                    _ => None,
                };
                match (kind, item) {
                    (Some(kind), Json::Array(members)) => {
                        // A path list (Devin `mcpServers`, #5024): every
                        // member keeps the owning kind.
                        for (index, member) in members.iter().enumerate() {
                            json_path.push(format!("[{index}]"));
                            out.push((json_path.clone(), manifest_member(key, kind, member)));
                            json_path.pop();
                        }
                    }
                    (Some(kind), _) => {
                        out.push((json_path.clone(), manifest_member(key, kind, item)));
                    }
                    (None, _) => manifest_refs(item, json_path, out),
                }
                json_path.pop();
            }
        }
        Json::Array(items) => {
            for (index, item) in items.iter().enumerate() {
                json_path.push(format!("[{index}]"));
                manifest_refs(item, json_path, out);
                json_path.pop();
            }
        }
        _ => {}
    }
}

fn collect_launcher_files(dir: &Path, out: &mut BTreeMap<PathBuf, Kind>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() {
            if !SKIP_DIRS.contains(&name.as_ref()) {
                collect_launcher_files(&path, out);
            }
        } else if kind.is_file() && LAUNCHER_FILES.contains(&name.as_ref()) {
            let kind = if name == "hooks.json" {
                Kind::Hooks
            } else {
                Kind::Mcp
            };
            out.insert(path, kind);
        }
    }
}

fn read_json(path: &Path) -> Result<Json, String> {
    let text = fs::read_to_string(path).map_err(|err| format!("cannot read: {err}"))?;
    parse_json(&text).map_err(|err| format!("invalid JSON: {err}"))
}

fn path_text(json_path: &[String]) -> String {
    let mut out = String::new();
    for part in json_path {
        if !part.starts_with('[') && !out.is_empty() {
            out.push('.');
        }
        out.push_str(part);
    }
    if out.is_empty() {
        out.push('$');
    }
    out
}

/// `path` relative to `root` when possible, for messages.
#[must_use]
pub fn display(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .into_owned()
}

#[cfg(test)]
