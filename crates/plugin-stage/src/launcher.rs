//! Launcher side of the packaging contract.
//!
//! A launcher is a host configuration string that runs a staged binary: a
//! hook `command` in `hooks.json`, or an MCP server `command` in `.mcp.json`
//! or `mcp.json` (also inline in a plugin manifest). Launchers always call
//! the generated dispatcher `${CLAUDE_PLUGIN_ROOT}/bin/<name>`, never a
//! platform directory, and the dispatcher picks the binary for the running
//! platform. [`check_launchers`] proves every such reference resolves to a
//! declared binary and has the form its role requires.
//!
//! The check is a closed allowlist (#4487 PM ruling after review #5018
//! round 3): every hook command must be byte for byte one reviewed template
//! instance; every MCP server object, command and args together, is a
//! canonical binary launcher or an inventory program (`uvx`) whose argv
//! matches its template (#5088 ruling); other strings are literal data that
//! may not name the plugin root (except as a plain relative path) or a `bin`
//! segment. No shell is parsed or approximated, so an unlisted spelling is
//! refused rather than classified.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Component, Path, PathBuf};

use toolkit_core::{parse_json, Json};

use crate::declaration::{BinarySpec, Declaration, Role};
use crate::BIN_DIR;

/// Plugin-root variables a launcher may start with.
pub const ROOT_VARS: [&str; 2] = ["CLAUDE_PLUGIN_ROOT", "CURSOR_PLUGIN_ROOT"];

/// Directories never scanned for launcher files: shipped skill content,
/// fixtures, tests, dependencies and the staged `bin/` directory itself.
const SKIP_DIRS: [&str; 7] = [
    "skills",
    "fixtures",
    "tests",
    "node_modules",
    "bin",
    "target",
    ".git",
];

/// Launcher configuration file names.
const LAUNCHER_FILES: [&str; 3] = ["hooks.json", ".mcp.json", "mcp.json"];

/// Plugin manifests that may point at, or inline, launcher configuration.
const MANIFESTS: [&str; 5] = [
    "plugin.json",
    ".claude-plugin/plugin.json",
    ".codex-plugin/plugin.json",
    ".cursor-plugin/plugin.json",
    ".devin-plugin/plugin.json",
];

/// The canonical fail-closed launcher of a guard hook: it runs the
/// dispatcher, forwards its output when it exits 0 and otherwise (missing
/// file, not executable, no binary for this platform, non-zero exit,
/// signal) prints a `PreToolUse` deny carrying `deny_reason`. This is the
/// #4412 launcher contract with the path moved to `bin/<name>`.
#[must_use]
pub fn guard_hook_command(root_var: &str, name: &str, deny_reason: &str) -> String {
    let deny = format!(
        r#"{{\"hookSpecificOutput\":{{\"hookEventName\":\"PreToolUse\",\"permissionDecision\":\"deny\",\"permissionDecisionReason\":\"{deny_reason}\"}}}}"#
    );
    format!(
        r#"sh -c 'if out=$("$0" 2>/dev/null); then printf %s "$out"; else printf %s "{deny}"; fi' "${{{root_var}}}/bin/{name}""#
    )
}

/// The canonical MCP server command of a staged binary.
#[must_use]
pub fn mcp_command(root_var: &str, name: &str) -> String {
    format!("${{{root_var}}}/bin/{name}")
}

/// The generated POSIX dispatcher staged at `bin/<name>`. It maps
/// `uname -s` / `uname -m` to one of the supported platform pairs, runs
/// `bin/<key>/<name>` (or `bin/<name>.exe` under Git Bash, MSYS or Cygwin on
/// Windows, `x86_64` or ARM64 through emulation) with the caller's arguments
/// and stdin, and exits 127 with a message on stderr when the platform is
/// unsupported (before any file lookup, #5025) or no binary is staged for it.
#[must_use]
pub fn dispatcher_script(name: &str) -> String {
    format!(
        r#"#!/bin/sh
# Generated by plugin-stage (#4487); do not edit. Runs the staged {name}
# binary for this platform. bin/manifest.json lists every staged file, its
# sha256 and the source commit it was built from.
case "$0" in */*) d=${{0%/*}} ;; *) d=. ;; esac
s=$(uname -s 2>/dev/null)
m=$(uname -m 2>/dev/null)
o=
a=
case "$s" in
  Linux) o=linux ;;
  Darwin) o=macos ;;
  MINGW*|MSYS*|CYGWIN*) o=windows ;;
esac
case "$m" in
  x86_64|amd64|x64) a=x86_64 ;;
  aarch64|arm64) a=aarch64 ;;
esac
if [ -z "$o" ] || [ -z "$a" ]; then
  printf '%s: unsupported platform (uname -s %s, uname -m %s); no staged binary runs here\n' "{name}" "$s" "$m" >&2
  exit 127
fi
if [ "$o" = windows ]; then b="$d/{name}.exe"; else b="$d/$o-$a/{name}"; fi
if [ ! -f "$b" ] || [ ! -x "$b" ]; then
  echo "{name}: no staged binary for $o-$a at $b; reinstall the plugin" >&2
  exit 127
fi
exec "$b" "$@"
"#
    )
}

/// A JSON launcher snippet for one declared binary, ready to paste into
/// `hooks.json` (guard and hook roles) or `.mcp.json` (MCP role).
///
/// # Errors
///
/// A `subprocess` binary (R-PKG-2) is spawned by code and has no launcher.
pub fn launcher_snippet(binary: &BinarySpec) -> Result<String, String> {
    let root = ROOT_VARS[0];
    let value = match &binary.role {
        Role::Subprocess => {
            return Err(format!(
                "{}/{} is declared subprocess: code spawns it directly and no launcher string may run it",
                binary.destination.key(),
                binary.name
            ))
        }
        Role::GuardHook { deny_reason } => Json::object(vec![
            ("type", Json::string("command")),
            (
                "command",
                Json::string(guard_hook_command(root, &binary.name, deny_reason)),
            ),
            ("timeout", Json::Int(5)),
        ]),
        Role::McpServer => Json::object(vec![
            ("type", Json::string("stdio")),
            ("command", Json::string(mcp_command(root, &binary.name))),
            ("args", Json::Array(Vec::new())),
        ]),
        Role::Hook => Json::object(vec![
            ("type", Json::string("command")),
            (
                "command",
                Json::string(format!("\"{}\"", mcp_command(root, &binary.name))),
            ),
        ]),
    };
    Ok(value.to_pretty_string())
}

/// Which host configuration a launcher string came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Hooks,
    Mcp,
}

/// One validated launcher reference.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LauncherRef {
    /// Plugin directory name.
    pub plugin: String,
    /// Declared binary name.
    pub name: String,
    /// Repository-relative launcher file and JSON path.
    pub location: String,
}

/// Result of [`check_launchers`].
#[derive(Debug, Default)]
pub struct LauncherReport {
    /// Contract violations; empty means the contract holds.
    pub problems: Vec<String>,
    /// Every valid reference to a declared binary.
    pub references: Vec<LauncherRef>,
    /// Every accepted string with the allowlist template it instantiates.
    pub accepted: Vec<TemplateMatch>,
    /// Number of launcher files scanned.
    pub files_scanned: usize,
}

/// One accepted launcher-file string and the allowlist template it matches
/// (see `docs/migration/plugin-binaries.md` section 4).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TemplateMatch {
    /// Repository-relative launcher file and JSON path.
    pub location: String,
    /// The string itself.
    pub value: String,
    /// Template id, for example `python-guard`, `guard-deny` or `mcp-argv`.
    pub template: &'static str,
}

impl LauncherReport {
    /// Declared plugin binaries no launcher references yet (informational: a
    /// binary may be staged before its launcher switch lands). Package
    /// destinations have no launchers, so they are never listed.
    #[must_use]
    pub fn unreferenced<'a>(&self, declaration: &'a Declaration) -> Vec<&'a BinarySpec> {
        declaration
            .binaries
            .iter()
            .filter(|binary| binary.plugin().is_some())
            .filter(|binary| {
                !self
                    .references
                    .iter()
                    .any(|r| binary.plugin() == Some(r.plugin.as_str()) && r.name == binary.name)
            })
            .collect()
    }
}

/// Scans every plugin under `plugins_root` and checks that each launcher
/// reference to a `bin/` entry names a binary `declaration` declares for that
/// plugin, goes through the dispatcher and has the form its role requires.
/// `repo_root` only shortens paths in messages.
#[must_use]
pub fn check_launchers(
    repo_root: &Path,
    plugins_root: &Path,
    declaration: &Declaration,
) -> LauncherReport {
    let mut report = LauncherReport::default();
    let mut plugins: Vec<PathBuf> = match fs::read_dir(plugins_root) {
        Ok(entries) => entries
            .filter_map(Result::ok)
            .map(|entry| entry.path())
            .filter(|path| path.is_dir())
            .collect(),
        Err(err) => {
            report.problems.push(format!(
                "{}: cannot read plugins directory: {err}",
                plugins_root.display()
            ));
            return report;
        }
    };
    plugins.sort();
    for plugin_dir in plugins {
        let plugin = plugin_dir
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default();
        let scan = PluginScan {
            repo_root,
            plugin_dir: &plugin_dir,
            plugin: &plugin,
            declaration,
        };
        scan.run(&mut report);
    }
    for plugin in declaration.plugins() {
        if !plugins_root.join(plugin).is_dir() {
            report.problems.push(format!(
                "{DECLARATION}: plugin {plugin} has no directory under {}",
                display(repo_root, plugins_root),
                DECLARATION = crate::DECLARATION_PATH
            ));
        }
    }
    report
}

struct PluginScan<'a> {
    repo_root: &'a Path,
    plugin_dir: &'a Path,
    plugin: &'a str,
    declaration: &'a Declaration,
}

impl PluginScan<'_> {
    fn run(&self, report: &mut LauncherReport) {
        let mut files = BTreeMap::new();
        collect_launcher_files(self.plugin_dir, &mut files);
        let mut inline = Vec::new();
        for manifest in MANIFESTS {
            let path = self.plugin_dir.join(manifest);
            if !path.is_file() {
                continue;
            }
            let rel = display(self.repo_root, &path);
            match read_json(&path) {
                Ok(root) => {
                    let mut found = Vec::new();
                    manifest_refs(&root, &mut Vec::new(), &mut found);
                    for (json_path, target) in found {
                        match target {
                            ManifestRef::File(kind, text) => match self.resolve(&path, &text) {
                                Ok(file) => {
                                    files.insert(file, kind);
                                }
                                Err(message) => report
                                    .problems
                                    .push(format!("{rel}: {}: {message}", path_text(&json_path))),
                            },
                            ManifestRef::Inline(kind, value) => {
                                inline.push((
                                    format!("{rel}: {}", path_text(&json_path)),
                                    kind,
                                    value,
                                ));
                            }
                            ManifestRef::Malformed(message) => report
                                .problems
                                .push(format!("{rel}: {}: {message}", path_text(&json_path))),
                        }
                    }
                }
                Err(message) => report.problems.push(format!("{rel}: {message}")),
            }
        }
        for (file, kind) in files {
            let rel = display(self.repo_root, &file);
            report.files_scanned += 1;
            match read_json(&file) {
                Ok(root) => self.scan_value(&rel, kind, &root, &mut Vec::new(), report),
                Err(message) => report.problems.push(format!("{rel}: {message}")),
            }
        }
        for (location, kind, value) in inline {
            report.files_scanned += 1;
            self.scan_value(&location, kind, &value, &mut Vec::new(), report);
        }
    }

    /// Resolves a manifest's launcher file reference inside the plugin.
    fn resolve(&self, manifest: &Path, text: &str) -> Result<PathBuf, String> {
        let relative: PathBuf = Path::new(text)
            .components()
            .filter(|part| !matches!(part, Component::CurDir))
            .collect();
        if relative.is_absolute()
            || relative.components().any(|part| {
                matches!(
                    part,
                    Component::ParentDir | Component::Prefix(_) | Component::RootDir
                )
            })
        {
            return Err(format!("launcher file {text:?} points outside the plugin"));
        }
        let from_root = self.plugin_dir.join(&relative);
        if from_root.is_file() {
            return Ok(from_root);
        }
        let from_manifest = manifest.parent().map(|dir| dir.join(&relative));
        match from_manifest {
            Some(path) if path.is_file() => Ok(path),
            _ => Err(format!("launcher file {text:?} does not exist")),
        }
    }

    fn scan_value(
        &self,
        location: &str,
        kind: Kind,
        value: &Json,
        json_path: &mut Vec<String>,
        report: &mut LauncherReport,
    ) {
        match value {
            Json::String(text) => self.scan_string(location, kind, text, json_path, report),
            Json::Array(items) => {
                for (index, item) in items.iter().enumerate() {
                    json_path.push(format!("[{index}]"));
                    self.scan_value(location, kind, item, json_path, report);
                    json_path.pop();
                }
            }
            Json::Object(pairs)
                if kind == Kind::Mcp
                    && pairs
                        .iter()
                        .any(|(key, _)| key == "command" || key == "args") =>
            {
                self.scan_server(location, pairs, json_path, report);
            }
            Json::Object(pairs) => {
                for (key, item) in pairs {
                    json_path.push(key.clone());
                    self.scan_value(location, kind, item, json_path, report);
                    json_path.pop();
                }
            }
            _ => {}
        }
    }

    /// Checks one MCP server object as a whole (#5088 ruling): `command`
    /// and `args` together. The command is either the canonical launcher of
    /// a declared `mcp-server` binary, whose args are literal data checked
    /// one by one, or exactly one [`MCP_PROGRAMS`] name, whose whole argv
    /// must match that program's template and whose object may hold only
    /// `type` (`stdio`), `command` and `args`. Program launchers, shells,
    /// interpreters and every other program are refused, so no accepted
    /// argument is ever re-split or evaluated by a wrapper (`env -S`).
    fn scan_server(
        &self,
        location: &str,
        pairs: &[(String, Json)],
        json_path: &mut Vec<String>,
        report: &mut LauncherReport,
    ) {
        let field = |name: &str| pairs.iter().find(|(key, _)| key == name).map(|(_, v)| v);
        let at = |json_path: &[String], key: &str| {
            let mut path = json_path.to_vec();
            path.push(key.to_string());
            format!("{location}: {}", path_text(&path))
        };
        let command = match field("command") {
            Some(Json::String(text)) => text,
            Some(_) => {
                report
                    .problems
                    .push(format!("{}: {REFUSED_MCP_SHAPE}", at(json_path, "command")));
                return;
            }
            None => {
                report
                    .problems
                    .push(format!("{}: {REFUSED_MCP_SHAPE}", at(json_path, "args")));
                return;
            }
        };
        json_path.push("command".to_string());
        let resolved = self.resolve_string(Kind::Mcp, command, json_path);
        json_path.pop();
        // A canonical binary server keeps literal args; a refused command
        // stays refused, and its other keys are still scanned as literal
        // data so a binary launcher hidden in its args is named too.
        let literal_rest = match resolved {
            Ok(accepted) => {
                let canonical = accepted.name.is_some();
                self.record(&at(json_path, "command"), command, accepted, report);
                canonical
            }
            Err(message) => {
                report
                    .problems
                    .push(format!("{}: {message}", at(json_path, "command")));
                true
            }
        };
        if literal_rest {
            for (key, item) in pairs.iter().filter(|(key, _)| key != "command") {
                json_path.push(key.clone());
                self.scan_value(location, Kind::Mcp, item, json_path, report);
                json_path.pop();
            }
            return;
        }
        let Some((program, template)) = MCP_PROGRAMS.iter().find(|(name, _)| name == command)
        else {
            report
                .problems
                .push(format!("{}: {REFUSED_MCP}", at(json_path, "command")));
            return;
        };
        for (key, item) in pairs {
            let allowed = match key.as_str() {
                "command" | "args" => true,
                "type" => matches!(item, Json::String(kind) if kind == "stdio"),
                _ => false,
            };
            if !allowed {
                report.problems.push(format!(
                    "{}: is not allowed in a {program} MCP server, which may hold only `type` \"stdio\", `command` and `args`; refused (fail closed)",
                    at(json_path, key)
                ));
            }
        }
        let args: Option<Vec<&str>> = match field("args") {
            Some(Json::Array(items)) => items.iter().map(Json::as_str).collect(),
            _ => None,
        };
        let ids = args.as_deref().and_then(|args| {
            let ids = template(args)?;
            args.iter()
                .all(|arg| self.literal(arg, true).is_ok())
                .then_some(ids)
        });
        match (args, ids) {
            (Some(args), Some(ids)) => {
                for (index, (arg, id)) in args.iter().zip(ids).enumerate() {
                    let mut path = json_path.clone();
                    path.extend(["args".to_string(), format!("[{index}]")]);
                    report.accepted.push(TemplateMatch {
                        location: format!("{location}: {}", path_text(&path)),
                        value: (*arg).to_string(),
                        template: id,
                    });
                }
            }
            _ => report.problems.push(format!(
                "{}: do not match the reviewed {program} argument template; refused (fail closed). {}",
                at(json_path, "args"),
                REFUSED_UVX_ARGS
            )),
        }
    }

    fn scan_string(
        &self,
        location: &str,
        kind: Kind,
        text: &str,
        json_path: &[String],
        report: &mut LauncherReport,
    ) {
        let at = format!("{location}: {}", path_text(json_path));
        match self.resolve_string(kind, text, json_path) {
            Ok(accepted) => self.record(&at, text, accepted, report),
            Err(message) => report.problems.push(format!("{at}: {message}")),
        }
    }

    /// Records one accepted string and, for a binary launcher, its
    /// reference.
    fn record(&self, at: &str, text: &str, accepted: Accepted, report: &mut LauncherReport) {
        if let Some(name) = accepted.name {
            report.references.push(LauncherRef {
                plugin: self.plugin.to_string(),
                name,
                location: at.to_string(),
            });
        }
        report.accepted.push(TemplateMatch {
            location: at.to_string(),
            value: text.to_string(),
            template: accepted.template,
        });
    }

    /// Resolves one launcher string against the closed template allowlist
    /// (#4487 PM ruling after review #5018 round 3). Nothing is classified
    /// as "bad shell": a string is accepted only when it is byte for byte one
    /// template instance, whose only variable part is a declared binary name
    /// or a plain plugin-relative path ([`is_relpath`]).
    /// - Any key: the exact canonical launcher of one of this plugin's
    ///   declared binaries (guard deny launcher, plain-hook reference, MCP
    ///   command), then checked for the form its role and key require.
    /// - A hook `command`: one of [`FILE_TEMPLATES`].
    /// - An MCP `command`: exactly one [`MCP_PROGRAMS`] name; the whole
    ///   server object is then checked by [`Self::scan_server`].
    /// - Any other string (MCP `args`, `matcher`, `url`, headers, ...) is
    ///   literal data: it may not name a plugin-root variable except as
    ///   exactly `${CLAUDE_PLUGIN_ROOT}/<relpath>`, may not hold a `bin`
    ///   path segment, and an MCP `args` element may not name a shell.
    ///
    /// Everything else is refused with a fixed message that names the file
    /// and key and does not echo the string.
    fn resolve_string(
        &self,
        kind: Kind,
        text: &str,
        json_path: &[String],
    ) -> Result<Accepted, String> {
        if let Some((binary, template)) = self.canonical_binary(text) {
            return match role_problem(binary, kind, text, json_path) {
                Some(message) => Err(message),
                None => Ok(Accepted {
                    template,
                    name: Some(binary.name.clone()),
                }),
            };
        }
        let key = json_path.last().map(String::as_str);
        let in_args = json_path
            .len()
            .checked_sub(2)
            .is_some_and(|at| json_path[at] == "args");
        let template = match (kind, key == Some("command")) {
            (Kind::Hooks, true) => self.hook_command(kind, text, json_path)?,
            (Kind::Mcp, true) => self.mcp_program(kind, text, json_path)?,
            (Kind::Mcp, false) if in_args => self.literal(text, true)?,
            _ => self.literal(text, false)?,
        };
        Ok(Accepted {
            template,
            name: None,
        })
    }

    /// The declared binary of this plugin whose canonical launcher `text` is
    /// byte for byte, with the template it instantiates.
    fn canonical_binary(&self, text: &str) -> Option<(&BinarySpec, &'static str)> {
        self.declaration
            .plugin_binaries(self.plugin)
            .find_map(|binary| {
                canonical_forms(binary)
                    .into_iter()
                    .find(|(form, _)| form == text)
                    .map(|(_, template)| (binary, template))
            })
    }

    /// A hook `command` that is not a binary launcher: exactly one
    /// [`FILE_TEMPLATES`] entry around a plain, symlink-free relpath.
    fn hook_command(
        &self,
        kind: Kind,
        text: &str,
        json_path: &[String],
    ) -> Result<&'static str, String> {
        let matches: Vec<(&'static str, &str)> = FILE_TEMPLATES
            .iter()
            .filter_map(|(id, prefix, suffix)| {
                let relpath = text.strip_prefix(prefix)?.strip_suffix(suffix)?;
                is_relpath(relpath).then_some((*id, relpath))
            })
            .collect();
        match matches.as_slice() {
            [(id, relpath)] => {
                self.symlink_free(relpath)?;
                Ok(id)
            }
            _ => Err(self.binary_hint(kind, text, json_path, HOOK_BIN_PREFIXES, '"', REFUSED)),
        }
    }

    /// An MCP `command` that is not a binary launcher: exactly one
    /// [`MCP_PROGRAMS`] name (#5088 ruling). Its args are checked by
    /// [`Self::scan_server`] against that program's argv template.
    fn mcp_program(
        &self,
        kind: Kind,
        text: &str,
        json_path: &[String],
    ) -> Result<&'static str, String> {
        MCP_PROGRAMS
            .iter()
            .find(|(program, _)| *program == text)
            .map(|(program, _)| *program)
            .ok_or_else(|| {
                self.binary_hint(kind, text, json_path, MCP_BIN_PREFIXES, ' ', REFUSED_MCP)
            })
    }

    /// Literal data (MCP `args` with `mcp_arg`, or any other key).
    fn literal(&self, text: &str, mcp_arg: bool) -> Result<&'static str, String> {
        let template = if mcp_arg { "mcp-argv" } else { "literal" };
        let upper = text.to_ascii_uppercase();
        if ROOT_VARS.iter().any(|root| upper.contains(root)) {
            let relpath = text
                .strip_prefix(ROOT_PREFIX)
                .filter(|relpath| is_relpath(relpath));
            return match relpath {
                Some(relpath) => self.symlink_free(relpath).map(|()| template),
                None => Err(REFUSED_ROOT_ARG.to_string()),
            };
        }
        if text
            .split(|c: char| !(c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '-')))
            .any(is_bin_segment)
        {
            return Err(REFUSED_ROOT_ARG.to_string());
        }
        if mcp_arg && is_shell(text.rsplit(['/', '\\']).next().unwrap_or(text)) {
            return Err(REFUSED_SHELL_ARG.to_string());
        }
        Ok(template)
    }

    /// Refuses a relpath any existing component of which is a symlink in
    /// the plugin: a plain spelling could otherwise lead into `bin/`.
    fn symlink_free(&self, relpath: &str) -> Result<(), String> {
        let mut path = self.plugin_dir.to_path_buf();
        for segment in relpath.split('/') {
            path.push(segment);
            if fs::symlink_metadata(&path).is_ok_and(|meta| meta.file_type().is_symlink()) {
                return Err(
                    "names a plugin path through a symlink; launcher paths must be plain files of the plugin; refused (fail closed)"
                        .to_string(),
                );
            }
        }
        Ok(())
    }

    /// The message for a refused `command`. When the string starts like a
    /// binary launcher (`prefixes`), the token up to `end` explains what is
    /// wrong with it (undeclared, platform path, `.exe`, wrong role); every
    /// other string gets the fixed `refused` message. Only a token that is a
    /// valid binary name is ever echoed.
    fn binary_hint(
        &self,
        kind: Kind,
        text: &str,
        json_path: &[String],
        prefixes: &[&str],
        end: char,
        refused: &str,
    ) -> String {
        let Some(rest) = prefixes.iter().find_map(|prefix| text.strip_prefix(prefix)) else {
            return refused.to_string();
        };
        let token = match rest.find(end) {
            Some(at) => &rest[..at],
            None if end == ' ' => rest,
            None => return refused.to_string(),
        };
        if token.is_empty() {
            "references the bin/ directory itself; launchers must name bin/<name>".to_string()
        } else if token.contains(['/', '\\']) {
            "references a file below bin/<name> directly; launchers must call the dispatcher bin/<name>, which selects the platform binary".to_string()
        } else if token.to_ascii_lowercase().ends_with(".exe") {
            "references bin/<name>.exe directly; launchers must call the dispatcher bin/<name>, which runs the .exe on Windows".to_string()
        } else if !crate::declaration::is_name(token) {
            refused.to_string()
        } else if let Some(binary) = self.declaration.binary(self.plugin, token) {
            role_problem(binary, kind, text, json_path).unwrap_or_else(|| refused.to_string())
        } else {
            format!(
                "references bin/{token}, which {} does not declare for plugin {}",
                crate::DECLARATION_PATH,
                self.plugin
            )
        }
    }
}

