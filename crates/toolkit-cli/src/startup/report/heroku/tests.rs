static COUNTER: AtomicUsize = AtomicUsize::new(0);

struct TempDir(PathBuf);

impl TempDir {
    fn new(label: &str) -> Self {
        let path = std::env::temp_dir().join(format!(
            "toolkit-heroku-{label}-{}-{}",
            std::process::id(),
            COUNTER.fetch_add(1, Ordering::Relaxed)
        ));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).expect("create temp dir");
        Self(path)
    }

    fn write(&self, name: &str, text: &str) {
        let path = self.0.join(name);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("create parent");
        }
        fs::write(path, text).expect("write file");
    }
}

impl Deref for TempDir {
    type Target = Path;

    fn deref(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn exec(values: &[&str]) -> (u8, String, String) {
    let args: Vec<OsString> = values.iter().map(OsString::from).collect();
    let mut out = Vec::new();
    let mut err = Vec::new();
    let code = run(&args, &mut out, &mut err);
    (
        code,
        String::from_utf8(out).expect("utf-8 stdout"),
        String::from_utf8(err).expect("utf-8 stderr"),
    )
}

/// The Python `run()` helper: writes the report, runs the command and returns
/// the exit status with stdout and stderr joined.
fn run_report(html: &str, dir: Option<&Path>, mode: Option<&str>) -> (u8, String) {
    let scratch = TempDir::new("report");
    scratch.write("migration-report.html", html);
    let report = scratch.join("migration-report.html");
    let report = report.to_str().expect("utf-8 path").to_string();
    let mut args = vec!["startup", "heroku-report", report.as_str()];
    let dir_text = dir.map(|d| d.to_str().expect("utf-8 path").to_string());
    if let Some(dir_text) = dir_text.as_deref() {
        args.extend(["--migration-dir", dir_text]);
    }
    if let Some(mode) = mode {
        args.extend(["--mode", mode]);
    }
    let (code, out, err) = exec(&args);
    (code, format!("{out}{err}"))
}

