fn what_if_section(columns: &[&str]) -> String {
    let heads = columns
        .iter()
        .map(|name| format!("<th scope=\"col\">{name}</th>"))
        .collect::<Vec<_>>()
        .concat();
    format!(
        "<section id=\"what-if-scenarios\"><table><thead><tr>{heads}</tr></thead>\
         <tbody><tr><td>Baseline</td></tr></tbody></table></section><section id=\"next-steps\">"
    )
}

