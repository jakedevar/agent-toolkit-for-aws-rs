#!/usr/bin/perl
# Generates table.rs beside this file: Unicode simple case folding
# (CaseFolding.txt status C and S) from Perl's core Unicode::UCD.
#
#   perl crates/toolkit-cli/src/launch/archive/casefold/gen_table.pl \
#     > crates/toolkit-cli/src/launch/archive/casefold/table.rs
#
# The Unicode version is Perl's; the Rust tests pin the row count and the
# version string, so a regeneration under another version is a visible diff.
use strict;
use warnings;
use Unicode::UCD qw(all_casefolds);

my $version = Unicode::UCD::UnicodeVersion();
my $all = all_casefolds();
my @rows;
for my $cp (sort { $a <=> $b } keys %$all) {
    my $simple = $all->{$cp}{simple} // '';
    next unless length $simple;
    my $to = hex $simple;
    push @rows, [$cp, $to] if $to != $cp;
}
my $count = scalar @rows;
print <<"HEAD";
//! DO NOT EDIT: generated by `gen_table.pl` beside this file from Perl's
//! `Unicode::UCD::all_casefolds` (Unicode $version).
//!
//! Unicode simple case folding: the CaseFolding.txt mappings of status C
//! (common) and S (simple), excluding F (full) and T (Turkic). Code points
//! not listed fold to themselves.

/// The Unicode version of [`SIMPLE_CASE_FOLDING`].
pub const UNICODE_VERSION: &str = "$version";

/// `(code point, simple case folding)` for every code point whose C or S
/// mapping is not itself, sorted by code point.
#[rustfmt::skip]
#[allow(clippy::unreadable_literal)]
pub const SIMPLE_CASE_FOLDING: [(u32, u32); $count] = [
HEAD
for (my $i = 0; $i < @rows; $i += 4) {
    my @line = map { sprintf '(0x%04X, 0x%04X),', @$_ } @rows[$i .. ($i + 3 < $#rows ? $i + 3 : $#rows)];
    print '    ', join(' ', @line), "\n";
}
print "];\n";
